// 誇大・排他・優良誤認のおそれがある表現は自動生成コンテンツに使わない。
// ここに載っている語が生成テキストに含まれていた場合はビルドを失敗させ、
// 事実確認なしに公開されることを防ぐ。
export const BANNED_WORDS = [
  "唯一", "日本一", "業界No.1", "業界NO.1", "No.1", "NO.1", "ナンバーワン",
  "絶対に", "100%改善", "必ず改善", "完全無欠", "最安", "業界最大手",
  "全国初", "県内唯一", "県内初",
];

export function assertCompliant(text) {
  for (const word of BANNED_WORDS) {
    if (text.includes(word)) {
      throw new Error(
        `コンプライアンスチェックに違反する表現が含まれています: "${word}"\n` +
          `該当テキスト: ${text.slice(0, 80)}...`
      );
    }
  }
}

function p(...paragraphs) {
  return paragraphs;
}

