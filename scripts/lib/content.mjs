export function buildArticleContent({ city, industry, angleKey, angleLabel }) {
  const builder = ANGLE_BUILDERS[angleKey];
  if (!builder) {
    throw new Error(`未定義の angleKey です: ${angleKey}`);
  }
  const content = builder(city, industry);

  const title = `${city}の${industry}向け ストレスチェック実施者代行(外部委託) | ${angleLabel}`;
  const metaDescription = `${city}で${industry}を営む事業所様向けに、ストレスチェックの実施者代行(外部委託)について「${angleLabel}」の観点から解説します。株式会社フジイコーポレーションが健康経営を支援します。`;

  const fullText = [
    title,
    metaDescription,
    content.lead,
    ...content.sections.flatMap((s) => [s.heading, ...s.paragraphs]),
    ...content.faq.flatMap((f) => [f.q, f.a]),
  ].join("\n");
  assertCompliant(fullText);

  return { title, metaDescription, lead: content.lead, sections: content.sections, faq: content.faq };
}
